test('Pack46 q16 decoder preserves normalized geometry values',()=>{
  const raw=Int16Array.from([0,16384,-16384,32767,-32767]);
  const encoded=Buffer.from(raw.buffer).toString('base64');
  const decoded=api.decodeBot46Q16(encoded);
  assert.equal(decoded.length,raw.length);
  assert.ok(Math.abs(decoded[0])<1e-7);
  assert.ok(Math.abs(decoded[1]-.5000153)<1e-5);
  assert.ok(Math.abs(decoded[2]+.5000153)<1e-5);
  assert.equal(decoded[3],1);
  assert.equal(decoded[4],-1);
});

