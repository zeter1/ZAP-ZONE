test('Pack46 generated manifest matches artifacts and q16 geometry contract',()=>{
  assert.equal(manifest.schema,1);
  assert.equal(manifest.packVersion,46);
  assert.equal(manifest.blenderVersion,'5.2.2 LTS');
  assert.deepEqual(Object.keys(manifest.components),names);
  for(const [name,stats] of Object.entries(manifest.components)){
    assert.ok(stats.triangles>0,`${name} must contain triangles`);
    assert.equal(stats.runtimeVertices,stats.triangles*3,`${name} runtime derivative must be non-indexed triangles`);
    assert.ok(stats.materialGroups>=1,`${name} must retain material groups`);
    assert.ok(stats.maxAbsLocalCoordinate<=1,`${name} must fit the q16 local coordinate range`);
  }
  const artifacts={
    glb:new URL('../assets/characters/models/zap-bot-modular-46.glb',import.meta.url),
    runtimeJs:new URL('../assets/characters/models/zap-bot-modular-46.runtime.js',import.meta.url),
    blend:new URL('../asset-staging/2026-10-06-bot-3d-pack-46/zap-bot-modular-46.blend',import.meta.url),
    preview:new URL('../asset-staging/2026-10-06-bot-3d-pack-46/zap-bot-modular-preview-46.png',import.meta.url),
    builder:new URL('../asset-staging/2026-10-06-bot-3d-pack-46/build_bot_3d.py',import.meta.url)
  };
  for(const [key,url] of Object.entries(artifacts))assert.deepEqual(fileIdentity(url),manifest.artifacts[key],`${key} must be regenerated by the canonical Blender builder`);
});

