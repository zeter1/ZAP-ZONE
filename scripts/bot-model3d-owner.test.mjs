test('Pack46 installs volume parts over hidden legacy surfaces without replacing gameplay nodes',()=>{
  const pts=Array.from({length:14},()=>node());
  const leftHand=node(),rightHand=node();
  const legRig={root:node(),left:makeLeg(),right:makeLeg()};
  const legacy=[{visible:true},{visible:true}];
  const visual=api.installBotModel46Rig({team:'enemy',pts,legRig,leftHand,rightHand,proceduralDecor:legacy});
  assert.ok(visual);
  assert.equal(Object.keys(visual).length,19);
  assert.equal(Object.keys(visual.roleModules).length,5);
  assert.ok(pts.every(p=>p.material.visible===false),'gameplay hit meshes remain but their surfaces are hidden: '+pts.map(p=>p.material.visible).join(','));
  assert.equal(leftHand.material.visible,false);
  assert.equal(rightHand.material.visible,false);
  assert.ok(legacy.every(x=>x.visible===false));
  assert.ok(pts[1].children.some(x=>x.name==='bot46-ZAP_Head'));
  assert.ok(pts[2].children.some(x=>x.name==='bot46-ZAP_Torso'));
  assert.ok(legRig.left.hip.children.some(x=>x.name==='bot46-ZAP_Thigh'));
  assert.ok(legRig.right.ankle.children.some(x=>x.name==='bot46-ZAP_Foot'));
  assert.equal(visual.head.rotation.y,Math.PI,'Pack46 head must face gameplay +Z instead of authored -Z');
  assert.equal(visual.torso.rotation.y,Math.PI,'Pack46 torso must share the gameplay-facing convention');
  assert.equal(visual.leftThigh.rotation.y,Math.PI,'Pack46 leg armor must not remain backwards');
  assert.equal(visual.leftHand.rotation.y,0,'weapon-driven hand already inherits the corrected pivot yaw and must not double-rotate');
});


test('Pack46 maps live AI roles and sniper weapons onto one visible Blender role module',()=>{
  const pts=Array.from({length:14},()=>node());
  const visual=api.installBotModel46Rig({
    team:'ally',pts,legRig:{root:node(),left:makeLeg(),right:makeLeg()},
    leftHand:node(),rightHand:node(),proceduralDecor:[]
  });
  const bot={model46:visual,role:'flankL',weapon:{key:'plasma'}};
  assert.equal(api.syncBotModel46RoleVariant(bot),true);
  assert.equal(visual.roleVariant,'flanker');
  assert.equal(visual.roleModules.flanker.visible,true);
  assert.equal(Object.values(visual.roleModules).filter(x=>x.visible).length,1);
  bot.role='anchor';bot.weapon={key:'sniper'};
  api.syncBotModel46RoleVariant(bot);
  assert.equal(visual.roleVariant,'sniper','sniper weapon appearance overrides the broader anchor chassis role');
  assert.equal(visual.roleModules.sniper.visible,true);
  assert.equal(Object.values(visual.roleModules).filter(x=>x.visible).length,1);
  assert.equal(api.botModel46RoleVariant('engineer','plasma'),'engineer');
  assert.equal(api.botModel46RoleVariant('assault','rifle'),'assault');
});
